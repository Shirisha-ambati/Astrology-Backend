export function createTranslator(locale) {
  const bundle = translations[locale] || translations.en;
  const fallbackBundle = translations.en;

  const lookup = (source, key) => key.split('.').reduce((value, part) => value?.[part], source);

  return (key) => lookup(bundle, key) ?? lookup(fallbackBundle, key) ?? key;
}
